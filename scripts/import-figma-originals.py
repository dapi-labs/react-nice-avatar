"""Convert committed Figma exports to JSX, preserving paths and export offsets."""
from pathlib import Path
import json, re
root=Path(__file__).resolve().parents[1]
manifest=json.loads((root/'assets/figma-originals/manifest.json').read_text())
names=['hoop','stud','surprised','sad','frown','pucker','nervous','down','eyelashesDown','eyeshadow','dougFunny','bald','originalBeard','scruff']
text='''// Generated by scripts/import-figma-originals.py. Original geometry is in assets/figma-originals.
import React from "react";
let nextId = 0;
export default class OriginalArtwork extends React.Component<{name: string; color?: string}> {
  private readonly artworkId = `nice-original-${++nextId}`;
  render() {
  const {name, color} = this.props;
  const id = this.artworkId;
  switch (name) {
'''
for item,name in zip(manifest,names):
    svg=(root/'assets/figma-originals'/f"{item['id'].replace(':','-')}.svg").read_text()
    body=svg[svg.index('>')+1:svg.rindex('</svg>')].strip()
    body=re.sub(r'([a-z]+)-([a-z]+)=',lambda m:m[1]+m[2].capitalize()+'=',body)
    body=body.replace('style="mask-type:alpha"','style={{maskType: "alpha"}}')
    body=re.sub(r'id="([^"]+)"',r'id={`${id}-\1`}',body)
    body=re.sub(r'="url\(#([^\)]+)\)"',r'={`url(#${id}-\1)`}',body)
    if name in ['hoop','stud']: body=body.replace('"#F4D150"','{color || "#F4D150"}')
    if name in ['dougFunny','scruff']: body=body.replace('"black"','{color || "black"}')
    if name=='originalBeard': body=body.replace('"#AC6651"','{color || "black"}')
    if name=='eyeshadow': body=body.replace('"#D2EFF3"','{color || "#D2EFF3"}')
    dx=item['renderBounds']['x']-item['bounds']['x']; dy=item['renderBounds']['y']-item['bounds']['y']
    text+=f'    case "{name}": return <g transform="translate({dx} {dy})">\n{body}\n</g>;\n'
text+='    default: return null;\n  }\n  }\n}\n'
(root/'src/originals/artwork.tsx').write_text(text)
